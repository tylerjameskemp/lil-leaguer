export function defaultActiveGameId(schedule: SeasonEvent[] = DEFAULT_SEASON_SCHEDULE) {
  return (
    schedule.find((event) => event.type === "game" && new Date(event.start) >= new Date())?.id ??
    schedule.find((event) => event.type === "game")?.id
  );
}

export function mergeSeasonSchedule(schedule?: SeasonEvent[]) {
  if (!schedule?.length) return DEFAULT_SEASON_SCHEDULE;

  const existing = new Map(schedule.map((event) => [event.id, event]));
  return DEFAULT_SEASON_SCHEDULE.map((event) => existing.get(event.id) ?? event);
}
